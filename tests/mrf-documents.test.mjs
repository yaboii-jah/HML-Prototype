const hash = bytes => createHash('sha256').update(bytes).digest('hex');
test('Canonical application origins handle internal host normalization and reject cross-origin writes', () => {
  const request = headers => new Request('http://localhost:3198/api/mrf-documents', { headers });
  assert.equal(sameApplicationOrigin(request({ Origin: 'http://127.0.0.1:3198' }), true, 'http://127.0.0.1:3198'), true);
  assert.equal(sameApplicationOrigin(request({}), true, 'http://127.0.0.1:3198'), false);
  assert.equal(sameApplicationOrigin(request({ Origin: 'https://example.invalid' }), true, 'http://127.0.0.1:3198'), false);
  assert.equal(sameApplicationOrigin(request({ Origin: 'http://127.0.0.1:3198', 'Sec-Fetch-Site': 'same-site' }), true, 'http://127.0.0.1:3198'), false);
  assert.equal(sameApplicationOrigin(request({ Origin: 'http://localhost:3198' }), true, ''), true);
});
test('Frozen approved-form generation preserves exact quantities and repeatable bytes', async () => {
  const quantity = '12345678901234567890.12345';
  const request = { ref: 'QA-MRF-0001', requestDate: '2026-11-03', requestedBy: 'Frozen Site', approvedBy: 'Frozen PM', purchaser: '', financeOfficer: '', specialInstructions: 'Frozen instructions',
    documents: [{ type: 'Supporting PDF', name: 'original.pdf' }], items: [{ quantity, name: 'Exact material', unit: 'pc', neededDate: '2026-11-04', purpose: 'Frozen purpose', location: 'Site', remarks: '' }] };
  const first = await generateMrfPdf(request, 'Frozen project', 'Frozen location', undefined, '2026-11-03T00:00:00Z');
  const second = await generateMrfPdf(request, 'Frozen project', 'Frozen location', undefined, '2026-11-03T00:00:00Z');
  assert.equal(hash(first), hash(second), 'A retried immutable snapshot has identical generated bytes');
  const pdf = await PDFDocument.load(first), text = pdf.getPages().flatMap(page => pageText(pdf, page).map(part => part.text)).join('');
  assert.ok(text.includes(quantity), 'Quantity was not rounded through a JavaScript number');
  assert.ok(text.includes('FROZEN PROJECT')); assert.ok(text.includes('QA-MRF-0001')); assert.ok(text.includes('original.pdf'));
});
test('Supporting PDF bounds and single ranges handle suffix, clamp and invalid requests', () => {
  assert.equal(validPdfSelection('support.pdf', MAX_SUPPORTING_PDF, 'a'.repeat(64)), true);
  for (const [name, size, sha] of [['x.jpg', 5, 'a'.repeat(64)], ['x.pdf', MAX_SUPPORTING_PDF + 1, 'a'.repeat(64)], ['x.pdf', 5, 'no']]) assert.equal(validPdfSelection(name, size, sha), false);
  assert.deepEqual(documentRange('bytes=5-20', 10), { start: 5, end: 9 });
  assert.deepEqual(documentRange('bytes=-4', 10), { start: 6, end: 9 });
  assert.deepEqual(documentRange('bytes=0-', 10), { start: 0, end: 9 });
  assert.equal(documentRange(null, 10), null);
  for (const value of ['bytes=-0', 'bytes=10-', 'bytes=6-3', 'bytes=0-1,3-5', 'bytes=999999999999999999999-']) assert.throws(() => documentRange(value, 10));
});
test('Structural PDF validation rejects signature-only, truncated, empty and encrypted PDFs', async () => {
  const pdf = await PDFDocument.create(); pdf.addPage();
  const bytes = await pdf.save(); await validateSupportingPdf(bytes);
  await assert.rejects(validateSupportingPdf(Buffer.from('%PDF- fake %%EOF')));
  await assert.rejects(validateSupportingPdf(bytes.subarray(0, bytes.length - 20)));
  const empty = await PDFDocument.create();
  await assert.rejects(validateSupportingPdf(await empty.save({ addDefaultPage: false })));
  // An encryption dictionary must be rejected even without a valid password.
  const encrypted = Buffer.from('%PDF-1.4\n1 0 obj << /Type /Catalog /Pages 2 0 R >> endobj\n2 0 obj << /Type /Pages /Kids [] /Count 0 >> endobj\n3 0 obj << /Filter /Standard /V 1 /R 2 /O (abc) /U (def) /P -4 >> endobj\ntrailer << /Root 1 0 R /Encrypt 3 0 R >>\n%%EOF');
  await assert.rejects(validateSupportingPdf(encrypted));
});
test('Drive IDs recover lost creation acknowledgements, validate descendants and verify exact bytes', async () => {
  const fake = await fakeDrive(), drive = createDriveGateway(fake.origin, async () => 'disposable-drive-token');
  try {
    const folderId = await drive.generateId(), tags = { hmlProjectId: randomUUID() };
    fake.faults.failCreateAfterCommit = true;
    await assert.rejects(drive.ensureFolder(folderId, fake.root, 'Project', tags));
    const folder = await drive.ensureFolder(folderId, fake.root, 'Project', tags);
    assert.equal(folder.id, folderId);
    assert.equal(fake.files.size, 2);
    await drive.validateFolder(folderId, fake.root);
    await assert.rejects(drive.validateFolder(fake.root, fake.root));
    fake.files.set('outside-folder', { id: 'outside-folder', name: 'Outside', mimeType: 'application/vnd.google-apps.folder', parents: [], capabilities: { canAddChildren: true } });
    await assert.rejects(drive.validateFolder('outside-folder', fake.root));
    const pdf = await PDFDocument.create(); pdf.addPage(); const bytes = await pdf.save();
    const id = await drive.generateId(), fileTags = { hmlUploadId: randomUUID() };
    const uri = await drive.begin(id, folderId, 'support.pdf', bytes.length, fileTags);
    assert.equal((await drive.transfer(uri, bytes.length)).offset, 0);
    fake.faults.loseFinalResponse = true;
    await assert.rejects(drive.transfer(uri, bytes.length, bytes, 0));
    assert.equal((await drive.get(id)).size, String(bytes.length));
    assert.deepEqual(await drive.verifyPdf(id, folderId, fileTags, bytes.length, hash(bytes)), Buffer.from(bytes));
    await assert.rejects(drive.verifyPdf(id, folderId, fileTags, bytes.length, '0'.repeat(64)));
    await assert.rejects(drive.verifyPdf(id, folderId, { hmlUploadId: 'foreign' }, bytes.length, hash(bytes)));
    const part = await drive.stream(id, { start: 0, end: 4 });
    assert.equal(part.status, 206); assert.equal(await part.text(), '%PDF-');
    await assert.rejects(drive.trash(id, { hmlUploadId: 'foreign' }));
    assert.equal((await drive.get(id)).trashed, false);
    await drive.trash(id, fileTags); await drive.trash(id, fileTags);
    assert.equal((await drive.get(id)).trashed, true);
    assert.equal(drive.validSession('https://example.invalid/upload/drive/v3/files?uploadType=resumable&upload_id=secret'), false);
  } finally { await fake.close(); }
});
